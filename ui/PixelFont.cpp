void draw(ImDrawList* d,ImVec2 p,float scale,ImU32 colour,std::string_view text) {
    float x=p.x;
    if(dotStyle!=0) {
        // One shape per font pixel.
        for(char c:text) {
            const uint8_t* rows=rowsFor(c);
            for(int r=0;r<glyphH;++r) for(int b=0;b<glyphW;++b) {
                if(!((rows[r]>>(glyphW-1-b))&1)) continue;
                float x0=x+static_cast<float>(b)*scale,y0=p.y+static_cast<float>(r)*scale,h=scale/2;
                switch(dotStyle) {
                case 1: d->AddCircleFilled({x0+h,y0+h},h*0.92f,colour,12); break;
                case 2: d->AddQuadFilled({x0+h,y0},{x0+scale,y0+h},{x0+h,y0+scale},{x0,y0+h},colour); break;
                case 3: d->AddRect({x0+0.5f,y0+0.5f},{x0+scale-0.5f,y0+scale-0.5f},colour,0,0,std::max(1.0f,scale*0.22f)); break;
                case 4: d->AddRectFilled({x0,y0},{x0+scale,y0+scale},colour,scale*0.35f); break;
                default: d->AddRectFilled({x0+scale*0.12f,y0+scale*0.12f},{x0+scale*0.88f,y0+scale*0.88f},colour); break;
                }
            }
            x+=static_cast<float>(advance)*scale;
        }
        return;
    }
    for(char c:text) {
        const uint8_t* rows=rowsFor(c);
        for(int r=0;r<glyphH;++r) {
            // Runs of set bits become one rectangle.
            for(int b=0;b<glyphW;) {
                if(!((rows[r]>>(glyphW-1-b))&1)) {++b; continue;}
                int e=b; while(e<glyphW && ((rows[r]>>(glyphW-1-e))&1)) ++e;
                d->AddRectFilled({x+static_cast<float>(b)*scale,p.y+static_cast<float>(r)*scale},{x+static_cast<float>(e)*scale,p.y+static_cast<float>(r+1)*scale},colour);
                b=e;
            }
        }
        x+=static_cast<float>(advance)*scale;
    }
}
