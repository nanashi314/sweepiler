const uint8_t* rowsFor(char c) {
    for(const auto& g:glyphs) if(g.c==c) return g.rows;
    c=static_cast<char>(std::toupper(static_cast<unsigned char>(c)));
    for(const auto& g:glyphs) if(g.c==c) return g.rows;
    for(const auto& g:glyphs) if(g.c=='?') return g.rows;
    return glyphs[0].rows;
}
